#[cfg(unix)]
fn create_private(path: &Path, bytes: &[u8]) -> Result<()> {
    layouts::check_path(path)?;
    let mut file = OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o600)
        .custom_flags(libc::O_NOFOLLOW | libc::O_NONBLOCK | libc::O_CLOEXEC)
        .open(path)
        .map_err(|_| "Launch artifact already exists or is unavailable")?;
    file.write_all(bytes)
        .and_then(|_| file.sync_all())
        .map_err(|_| "Cannot persist launch artifact")?;
    File::open(path.parent().ok_or("Launch artifact has no parent")?)
        .and_then(|f| f.sync_all())
        .map_err(|_| "Cannot sync launch directory".into())
}
