struct Executable {
    device: u64,
    inode: u64,
    size: u64,
    modified: i64,
    modified_ns: i64,
    changed: i64,
    changed_ns: i64,
}
#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Plan {
    pub spec: Spec,
    native: Executable,
    daemon: Executable,
    #[serde(default)]
    entrypoint: Option<Executable>,
    hooks: Vec<u8>,
}
impl Plan {
    pub fn path(&self) -> PathBuf {
        self.spec
            .registration
            .directory
            .join("hook-launch")
            .join(format!("{}.json", self.spec.registration.id))
    }
    pub fn plugin(&self) -> PathBuf {
        self.spec
            .registration
            .directory
            .join("hook-launch")
            .join(format!("{}-plugin", self.spec.registration.id))
    }
    /// Reviewed create-only artifact. Existing profile rollback receipts do not
    /// own this file; cleanup must compare these exact generated bytes first.
    pub fn native_hook_file(&self) -> Option<PathBuf> {
        self.spec.hook_profile.as_ref().map(|profile| {
            profile
                .join("hooks")
                .join(format!("daedalus-{}.json", self.spec.registration.id))
        })
    }
    pub fn fingerprint(&self) -> Result<String> {
        Ok(format!(
            "{:x}",
            Sha256::digest(serde_json::to_vec(self).map_err(|_| "Cannot encode launch plan")?)
        ))
    }
    pub fn command(&self) -> Vec<String> {
        let mut args = match self.spec.registration.scope.harness {
            Harness::Grok => vec![
                "--no-leader".into(),
                "--no-auto-update".into(),
                "--session-id".into(),
                self.spec.registration.scope.conversation.clone(),
            ],
            Harness::Pi => vec![
                self.spec
                    .entrypoint
                    .as_ref()
                    .map(|p| p.to_string_lossy().into_owned())
                    .unwrap_or_default(),
                "--session-id".into(),
                self.spec.registration.scope.conversation.clone(),
                "--session-dir".into(),
                self.plugin()
                    .join("sessions")
                    .to_string_lossy()
                    .into_owned(),
                "--extension".into(),
                self.plugin()
                    .join("daedalus.mjs")
                    .to_string_lossy()
                    .into_owned(),
            ],
            _ => vec![
                "--session-id".into(),
                self.spec.registration.scope.conversation.clone(),
                "--plugin-dir".into(),
                self.plugin().to_string_lossy().into_owned(),
            ],
        };
        if let Some(model) = &self.spec.model {
            args.extend(["--model".into(), model.clone()]);
        }
        args
    }
}
pub(crate) fn validate_executable(path: &Path, native: bool) -> Result<()> {
    executable(path, native).map(|_| ())
}
#[cfg(unix)]
fn executable(path: &Path, native: bool) -> Result<Executable> {
    layouts::check_path(path)?;
    let mut file = OpenOptions::new()
        .read(true)
        .custom_flags(libc::O_NOFOLLOW | libc::O_NONBLOCK | libc::O_CLOEXEC)
        .open(path)
        .map_err(|_| "Cannot open launch executable")?;
    let meta = file
        .metadata()
        .map_err(|_| "Cannot inspect launch executable")?;
    if !meta.is_file()
        || meta.mode() & 0o111 == 0
        || meta.mode() & 0o022 != 0
        || ![0, unsafe { libc::geteuid() }].contains(&meta.uid())
    {
        return Err("Unsafe launch executable".into());
    }
    if native {
        let mut magic = [0; 4];
        file.read_exact(&mut magic)
            .map_err(|_| "Cannot read native executable")?;
        if &magic != b"\x7fELF" {
            return Err("First-launch registration requires a native ELF provider binary".into());
        }
    }
    Ok(Executable {
        device: meta.dev(),
        inode: meta.ino(),
        size: meta.len(),
        modified: meta.mtime(),
        modified_ns: meta.mtime_nsec(),
        changed: meta.ctime(),
        changed_ns: meta.ctime_nsec(),
    })
}
