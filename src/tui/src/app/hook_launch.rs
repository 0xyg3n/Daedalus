/// Persist only a reviewed plan. No provider is launched and no live registration
/// is created here. The same plan cannot later be consumed twice.
pub fn save(plan: &Plan, expected_sha: &str, now_ms: u64) -> Result<PathBuf> {
    let _guard =
        hook_runtime::active_guard(&plan.spec.registration.directory).map_err(|e| e.to_string())?;
    if plan.fingerprint()? != expected_sha
        || prepare(plan.spec.clone(), now_ms)?.fingerprint()? != expected_sha
    {
        return Err("Launch plan changed; review again".into());
    }
    let path = plan.path();
    private_dir(path.parent().ok_or("Launch plan has no parent")?)?;
    create_private(
        &path,
        &serde_json::to_vec(plan).map_err(|_| "Cannot encode launch plan")?,
    )?;
    Ok(path)
}
pub struct Activated {
    pub hook_profile: Option<PathBuf>,
    pub registration: PathBuf,
    pub program: PathBuf,
    /// argv[0] for the exec: the provider's command name, so terminal
    /// backends that detect agents by command (Herdr) recognize it.
    pub command_name: Option<&'static str>,
    pub arguments: Vec<String>,
    pub working_directory: PathBuf,
}
/// Bind to the actual wrapper process, verify its terminal/ancestry, then persist
/// before exec. Isolated fixtures call this function without executing a provider.
#[cfg(unix)]
pub fn activate(path: &Path, terminals: &Terminals, now_ms: u64) -> Result<Activated> {
    let bytes = layouts::read_private(path)?.ok_or("Launch plan does not exist")?;
    let plan: Plan = serde_json::from_slice(&bytes).map_err(|_| "Invalid launch plan")?;
    let _guard =
        hook_runtime::active_guard(&plan.spec.registration.directory).map_err(|e| e.to_string())?;
    if path != plan.path()
        || prepare(plan.spec.clone(), now_ms)?.fingerprint()? != plan.fingerprint()?
    {
        return Err("Launch plan expired or changed".into());
    }
    let pid = std::process::id();
    let file = OpenOptions::new()
        .read(true)
        .custom_flags(libc::O_NOFOLLOW | libc::O_NONBLOCK)
        .open(terminals.proc_root.join(pid.to_string()).join("stat"))
        .map_err(|_| "Cannot inspect launch process")?;
    let mut bytes = Vec::new();
    file.take(8193)
        .read_to_end(&mut bytes)
        .map_err(|_| "Cannot inspect launch process")?;
    if bytes.len() > 8192 {
        return Err("Invalid launch process evidence".into());
    }
    let start_ticks = std::str::from_utf8(&bytes)
        .ok()
        .and_then(|s| s.rsplit_once(')'))
        .and_then(|(_, s)| s.split_whitespace().nth(19))
        .and_then(|s| s.parse().ok())
        .ok_or("Invalid launch process generation")?;
    let mut registration = plan.spec.registration.clone();
    registration.harness_process = Some(ProcessIdentity { pid, start_ticks });
    NativeVerifier {
        terminals: terminals.clone(),
    }
    .verify(&registration)
    .map_err(|_| "Launch process does not own the selected foreground terminal")?;
    // Claim before mutations; uncertain/crashed starts require a new reviewed plan.
    create_private(&path.with_extension("claimed"), b"claimed\n")?;
    let plugin = plan.plugin();
    private_dir(&plugin)?;
    if plan.spec.registration.scope.harness == Harness::Grok {
        let profile = plan
            .spec
            .hook_profile
            .as_ref()
            .ok_or("Grok profile is missing")?;
        private_dir(&profile.join("hooks"))?;
        create_private(
            &profile
                .join("hooks")
                .join(format!("daedalus-{}.json", plan.spec.registration.id)),
            &plan.hooks,
        )?;
    } else if plan.spec.registration.scope.harness == Harness::Pi {
        private_dir(&plugin.join("sessions"))?;
        create_private(&plugin.join("daedalus.mjs"), &plan.hooks)?;
    } else {
        private_dir(&plugin.join("hooks"))?;
        create_private(&plugin.join("hooks/hooks.json"), &plan.hooks)?;
    }
    let registration = hook_runtime::install(&registration).map_err(|e| e.to_string())?;
    Ok(Activated {
        hook_profile: plan.spec.hook_profile.clone(),
        registration,
        program: plan.spec.native_binary.clone(),
        command_name: match plan.spec.registration.scope.harness {
            Harness::Claude => Some("claude"),
            Harness::Grok => Some("grok"),
            _ => None,
        },
        arguments: plan.command(),
        working_directory: plan.spec.working_directory,
    })
}
