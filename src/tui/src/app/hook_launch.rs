#[cfg(unix)]
fn uuid(value: &str) -> bool {
    value.len() == 36
        && value.bytes().enumerate().all(|(i, b)| {
            if [8, 13, 18, 23].contains(&i) {
                b == b'-'
            } else {
                b.is_ascii_hexdigit()
            }
        })
}
/// Read-only preparation. The template contains no process and is never installed.
#[cfg(unix)]
pub fn prepare(spec: Spec, now_ms: u64) -> Result<Plan> {
    let r = &spec.registration;
    r.validate().map_err(|e| e.to_string())?;
    if !matches!(
        r.scope.harness,
        Harness::Claude | Harness::Pi | Harness::Grok
    ) || r.harness_process.is_some()
        || !uuid(&r.scope.conversation)
    {
        return Err(
            "Launch requires a supported harness, fresh UUID and an unbound registration template"
                .into(),
        );
    }
    if spec.expires_ms <= now_ms || spec.expires_ms.saturating_sub(now_ms) > 600_000 {
        return Err("Launch approval must expire within ten minutes".into());
    }
    if spec.model.as_ref().is_some_and(|s| {
        s.is_empty() || s.len() > 256 || s.starts_with('-') || s.chars().any(char::is_control)
    }) {
        return Err("Invalid launch model".into());
    }
    layouts::check_path(&spec.working_directory)?;
    if !fs::metadata(&spec.working_directory).is_ok_and(|m| m.is_dir()) {
        return Err("Launch working directory is unavailable".into());
    }
    if r.scope.harness != Harness::Grok && spec.hook_profile.is_some() {
        return Err("Only Grok launch accepts a native hooks profile".into());
    }
    if r.scope.harness == Harness::Grok {
        let profile = spec
            .hook_profile
            .as_ref()
            .ok_or("Grok requires its selected native profile")?;
        layouts::check_path(profile)?;
        let meta = fs::metadata(profile).map_err(|_| "Grok profile is unavailable")?;
        if !meta.is_dir() || meta.uid() != unsafe { libc::geteuid() } || meta.mode() & 0o077 != 0 {
            return Err("Grok profile must be private and owned".into());
        }
        let target = profile
            .join("hooks")
            .join(format!("daedalus-{}.json", r.id));
        layouts::check_path(&target)?;
        if target.exists() || r.transcript.is_some() || spec.entrypoint.is_some() {
            return Err(
                "Grok requires a fresh hook file, native binary and no unverified transcript"
                    .into(),
            );
        }
    } else if r.scope.harness == Harness::Pi {
        use super::hooks::EventKind;
        if [
            EventKind::SessionStart,
            EventKind::UserPromptSubmit,
            EventKind::Activity,
            EventKind::PostToolUse,
            EventKind::AssistantResponse,
            EventKind::Stop,
            EventKind::Settled,
            EventKind::SessionEnd,
        ]
        .iter()
        .any(|e| !r.events.contains(e))
        {
            return Err("Pi launch requires the full native extension lifecycle event set".into());
        }
        if r.transcript.is_some() || spec.entrypoint.is_none() {
            return Err("Pi launch requires an explicit CLI entrypoint and provider-managed transcript path".into());
        }
        let plugin = r
            .directory
            .join("hook-launch")
            .join(format!("{}-plugin", r.id));
        layouts::check_path(&plugin)?;
        if plugin.exists() {
            return Err("Pi launch requires fresh isolated session storage".into());
        }
    } else {
        if spec.entrypoint.is_some() {
            return Err("Claude launch does not accept a script entrypoint".into());
        }
        let transcript = r
            .transcript
            .as_ref()
            .ok_or("Launch requires an explicit expected transcript path")?;
        if transcript.file_name().and_then(|s| s.to_str())
            != Some(format!("{}.jsonl", r.scope.conversation).as_str())
            || transcript.exists()
        {
            return Err("Launch requires a fresh transcript path for its UUID".into());
        }
    }
    if r.path().exists() {
        return Err("Launch registration already exists".into());
    }
    let hooks = hook_install::launch_hooks(r, &spec.daedalus_binary, &spec.observed_version)?;
    Ok(Plan {
        native: executable(&spec.native_binary, true)?,
        daemon: executable(&spec.daedalus_binary, true)?,
        entrypoint: spec
            .entrypoint
            .as_deref()
            .map(|p| executable(p, false))
            .transpose()?,
        spec,
        hooks,
    })
}
