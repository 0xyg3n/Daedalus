#[cfg(unix)]
fn private_dir(path: &Path) -> Result<()> {
    layouts::check_path(path)?;
    match fs::DirBuilder::new().mode(0o700).create(path) {
        Ok(()) => (),
        Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => (),
        Err(_) => return Err("Cannot create launch directory".into()),
    }
    let meta = fs::symlink_metadata(path).map_err(|_| "Cannot inspect launch directory")?;
    if !meta.is_dir() || meta.uid() != unsafe { libc::geteuid() } || meta.mode() & 0o077 != 0 {
        return Err("Launch directory must be private and owned".into());
    }
    Ok(())
}
