/// Only explicit CLI launch calls exec. Provider authentication and trust prompts
/// remain with the provider. An exec failure leaves the one-shot claim for audit.
#[cfg(unix)]
pub fn launch(path: &Path, now_ms: u64) -> Result<()> {
    let activation = activate(path, &Terminals::default(), now_ms)?;
    // This process is the explicit one-shot launcher, never the TUI parent.
    // Native session transcripts created after exec must remain private.
    unsafe {
        libc::umask(0o077);
    }
    let mut command = Command::new(activation.program);
    if let Some(name) = activation.command_name {
        command.arg0(name);
    }
    if let Some(profile) = activation.hook_profile {
        command.env("GROK_HOME", profile);
    }
    let error = command
        .args(activation.arguments)
        .current_dir(activation.working_directory)
        // Do not let inherited runtime preload options bypass reviewed code.
        .env_remove("NODE_OPTIONS")
        .env_remove("NODE_PATH")
        .exec();
    let _ = error;
    Err("Native harness exec failed; launch was not retried".into())
}
