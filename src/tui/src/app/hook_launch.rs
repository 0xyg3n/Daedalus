#[allow(unused_variables)]
fn process_start(root: &Path, pid: u32) -> Result<u64> {
    Err("Guided first-launch requires Unix exec; on Windows start the harness normally, then configure hooks for its existing session".into())
}
fn require_exited(root: &Path, process: &ProcessIdentity) -> Result<()> {
    if process.pid == 0 || process.start_ticks == 0 {
        return Err("Recorded process identity is invalid".into());
    }
    // A missing PID is evidence only in a readable process tree with our own
    // process present. Missing stat in an existing PID directory is ambiguous.
    process_start(root, std::process::id())?;
    let mut found = false;
    for entry in fs::read_dir(root).map_err(|_| "Process tree is unavailable")? {
        let entry = entry.map_err(|_| "Cannot inspect process tree")?;
        if entry.file_name() == process.pid.to_string().as_str() {
            found = true;
        }
    }
    if !found {
        return if root
            .join(process.pid.to_string())
            .try_exists()
            .map_err(|_| "Cannot recheck process")?
        {
            Err("Process changed during cleanup review".into())
        } else {
            Ok(())
        };
    }
    if process_start(root, process.pid)? == process.start_ticks {
        return Err("Original harness process is still present".into());
    }
    Ok(())
}
/// Preview is read-only. Retained private launch and registration records must
/// match the exact generated file, regardless of the original launch expiry.
pub fn cleanup_preview(path: &Path, proc_root: &Path) -> Result<Cleanup> {
    let bytes = layouts::read_private(path)?.ok_or("Launch plan is missing")?;
    let plan: Plan = serde_json::from_slice(&bytes).map_err(|_| "Invalid launch plan")?;
    if path != plan.path() || plan.spec.registration.scope.harness != Harness::Grok {
        return Err("Cleanup requires an exact Grok launch plan".into());
    }
    let _guard =
        hook_runtime::active_guard(&plan.spec.registration.directory).map_err(|e| e.to_string())?;
    let registration_bytes = layouts::read_private(&plan.spec.registration.path())?
        .ok_or("Launch registration is missing")?;
    let mut registration: Registration =
        serde_json::from_slice(&registration_bytes).map_err(|_| "Invalid launch registration")?;
    registration.validate().map_err(|e| e.to_string())?;
    let process = registration
        .harness_process
        .take()
        .ok_or("Recorded process identity is missing")?;
    if serde_json::to_value(&registration).map_err(|_| "Invalid registration")?
        != serde_json::to_value(&plan.spec.registration)
            .map_err(|_| "Invalid launch registration")?
    {
        return Err("Registration no longer matches this launch".into());
    }
    if layouts::read_private(&path.with_extension("claimed"))?.as_deref() != Some(b"claimed\n") {
        return Err("Launch activation evidence is missing".into());
    }
    require_exited(proc_root, &process)?;
    let hook_file = plan
        .native_hook_file()
        .ok_or("Native hook file is missing")?;
    let hooks = layouts::read_private(&hook_file)?.ok_or("Native hook file is already absent")?;
    let generated = hook_install::launch_hooks(
        &plan.spec.registration,
        &plan.spec.daedalus_binary,
        &plan.spec.observed_version,
    )?;
    if hooks != plan.hooks || hooks != generated {
        return Err("Native hook file changed; cleanup refused".into());
    }
    Ok(Cleanup {
        launch_plan: path.into(),
        hook_file,
        process,
        plan_sha: format!("{:x}", Sha256::digest(bytes)),
        registration_sha: format!("{:x}", Sha256::digest(registration_bytes)),
        hook_sha: format!("{:x}", Sha256::digest(hooks)),
    })
}
pub fn cleanup_apply(path: &Path, approved: &str, proc_root: &Path) -> Result<PathBuf> {
    let review = cleanup_preview(path, proc_root)?;
    let bytes = layouts::read_private(path)?.ok_or("Launch plan is missing")?;
    let plan: Plan = serde_json::from_slice(&bytes).map_err(|_| "Invalid launch plan")?;
    let _guard =
        hook_runtime::active_guard(&plan.spec.registration.directory).map_err(|e| e.to_string())?;
    let _lock = hook_install::lock(&plan.spec.registration.directory)?;
    let current = cleanup_preview(path, proc_root)?;
    if current.fingerprint()? != approved || current.fingerprint()? != review.fingerprint()? {
        return Err("Cleanup review changed; preview again".into());
    }
    require_exited(proc_root, &current.process)?;
    fs::remove_file(&current.hook_file).map_err(|_| "Cannot remove reviewed hook file")?;
    File::open(
        current
            .hook_file
            .parent()
            .ok_or("Hook file has no parent")?,
    )
    .and_then(|f| f.sync_all())
    .map_err(|_| "Hook removal persistence is uncertain")?;
    Ok(current.hook_file)
}
